def _collect_parameters(value: object) -> tuple[Parameter, ...]:
    """Recursively collect fit Parameters from model declarations/plugins."""

    if isinstance(value, Parameter):
        return (value,)
    parameters = getattr(value, "parameters", None)
    if parameters is not None and not callable(parameters):
        if isinstance(parameters, dict):
            return tuple(
                item for item in parameters.values() if isinstance(item, Parameter)
            )
        try:
            return tuple(item for item in parameters if isinstance(item, Parameter))
        except TypeError:
            pass
    if is_dataclass(value) and not isinstance(value, type):
        found = []
        for field in fields(value):
            found.extend(_collect_parameters(getattr(value, field.name)))
        return tuple(found)
    if isinstance(value, dict):
        return tuple(
            parameter
            for item in value.values()
            for parameter in _collect_parameters(item)
        )
    if isinstance(value, (tuple, list)):
        return tuple(
            parameter for item in value for parameter in _collect_parameters(item)
        )
    return ()


def _nominal_float(value: object | None, fallback: float) -> float:
    """Resolve the nominal numerical value used to freeze an integration scheme."""

    if value is None:
        return float(fallback)
    if isinstance(value, Parameter):
        return float(value.value)
    return float(value)


def _symmetrized_mass_pairs(
    pair: tuple[int, int],
    final_state_ids: tuple[int, int, int],
) -> tuple[tuple[int, int], ...]:
    """Return invariant-mass pairs generated by identical-particle symmetry."""

    unique: set[tuple[int, int]] = set()
    for permutation in permutations(range(3)):
        if all(
            final_state_ids[index] == final_state_ids[permutation[index]]
            for index in range(3)
        ):
            mapped = tuple(sorted(permutation[index] for index in pair))
            unique.add(mapped)
    return tuple(sorted(unique))


def _validate_positive_quantity(value: object, label: str, *, allow_zero: bool) -> None:
    parameter = value if isinstance(value, Parameter) else None
    nominal = float(parameter.value if parameter is not None else value)
    invalid = nominal < 0.0 if allow_zero else nominal <= 0.0
    if invalid:
        comparator = "non-negative" if allow_zero else "positive"
        raise ValueError(f"{label} must be {comparator}, got {nominal}")

    if parameter is not None and parameter.bounds is not None:
        lower, _ = parameter.bounds
        if lower is not None:
            invalid_lower = lower < 0.0 if allow_zero else lower <= 0.0
            if invalid_lower:
                comparator = "non-negative" if allow_zero else "positive"
                raise ValueError(
                    f"lower bound for {label} must be {comparator}, got {lower}"
                )


@dataclass(frozen=True)
class DecayChannel:
    """Parent particle and ordered three-body final state."""

    parent: str
    final_state: tuple[str, str, str]

    def __post_init__(self) -> None:
        if len(self.final_state) != 3:
            raise ValueError("DecayChannel requires exactly three final-state particles")
        if self.parent_mass <= sum(self.daughter_masses):
            raise ValueError(
                "parent mass must exceed the sum of final-state masses for a physical three-body decay"
            )

    @classmethod
    def from_particles(
        cls, parent: str, final_state: Sequence[str]
    ) -> DecayChannel:
        """Build a three-body channel from names in the particle database."""
        return cls(parent, tuple(final_state))

    @property
    def parent_mass(self) -> float:
        """Parent particle mass in GeV, looked up by name from `particle`."""
        return _mass_gev(self.parent)

    @property
    def daughter_masses(self) -> tuple[float, float, float]:
        """Final-state masses in GeV, in `final_state` order."""
        return tuple(_mass_gev(name) for name in self.final_state)

    @property
    def final_state_ids(self) -> tuple[int, int, int]:
        """PDG IDs of the final-state particles, in `final_state` order."""
        return tuple(int(_particle(name).pdgid) for name in self.final_state)


@dataclass(frozen=True)
class Resonance:
    """Declarative resonance component with interchangeable dynamics plugins.

    ``normalize_form_factors=True`` makes both amplitude barriers unity at
    the pole. False uses raw Laura++ primed barriers. This is independent of
    ``normalize_component`` (unit-integral component rescaling) and does not
    change the barrier ratio in the running width.
    """

    name: str
    pair: tuple[int, int]
    coefficient: object
    lineshape: object = RelativisticBreitWigner()
    angular: object = CovariantAngular()
    mass: object | None = None
    width: object | None = None
    spin: int | None = None
    resonance_radius: object = 1.5
    parent_radius: object = 5.0
    bachelor_momentum_frame: Literal["resonance", "parent"] = "resonance"
    normalize_component: bool | None = None
    normalize_form_factors: bool = True
    particle_name: str | None = None

    def __post_init__(self) -> None:
        if len(set(self.pair)) != 2 or any(
            index not in (0, 1, 2) for index in self.pair
        ):
            raise ValueError(
                "resonance pair must contain two distinct indices from 0, 1, 2"
            )
        if self.mass is not None:
            _validate_positive_quantity(self.mass, f"{self.name}.mass", allow_zero=False)
        if self.width is not None:
            _validate_positive_quantity(self.width, f"{self.name}.width", allow_zero=True)
        _validate_positive_quantity(self.resonance_radius, f"{self.name}.resonance_radius", allow_zero=True)
        _validate_positive_quantity(self.parent_radius, f"{self.name}.parent_radius", allow_zero=True)
        if self.spin is not None and (self.spin < 0 or int(self.spin) != self.spin):
            raise ValueError("resonance spin must be a non-negative integer")
        if self.bachelor_momentum_frame not in {"resonance", "parent"}:
            raise ValueError(
                "bachelor_momentum_frame must be either 'resonance' or 'parent'"
            )
        if self.normalize_component is not None and not isinstance(
            self.normalize_component, bool
        ):
            raise ValueError("normalize_component must be a boolean or None")
        if self.particle_name is not None and (
            not isinstance(self.particle_name, str) or not self.particle_name
        ):
            raise ValueError("particle_name must be a nonempty string or None")

    @classmethod
    def from_particle(
        cls,
        particle_name: str,
        *,
        pair: tuple[int, int],
        coefficient: object,
        name: str | None = None,
        lineshape: object = RelativisticBreitWigner(),
        angular: object = CovariantAngular(),
        mass: object | None = None,
        width: object | None = None,
        spin: int | None = None,
        resonance_radius: object = 1.5,
        parent_radius: object = 5.0,
        bachelor_momentum_frame: Literal["resonance", "parent"] = "resonance",
        normalize_component: bool | None = None,
        normalize_form_factors: bool = True,
    ) -> Resonance:
        """Build a resonance from the same particle lookup used by ``Isobar``.

        Explicit mass, width and spin values take precedence. ``name`` may set
        a distinct amplitude-component name while ``particle_name`` retains the
        database identity used for provenance and unresolved properties.
        """
        resolved_mass, resolved_width, resolved_spin = _resolve_resonance_properties(
            particle_name,
            mass=mass,
            width=width,
            spin=spin,
            context="Three-body resonance component",
            validate_name=True,
        )
        return cls(
            name=particle_name if name is None else name,
            pair=pair,
            coefficient=coefficient,
            lineshape=lineshape,
            angular=angular,
            mass=resolved_mass,
            width=resolved_width,
            spin=resolved_spin,
            resonance_radius=resonance_radius,
            parent_radius=parent_radius,
            bachelor_momentum_frame=bachelor_momentum_frame,
            normalize_component=normalize_component,
            normalize_form_factors=normalize_form_factors,
            particle_name=particle_name,
        )


def _resolved_resonance_properties(
    component: Resonance,
) -> tuple[object, object, int]:
    particle_name = component.particle_name or component.name
    return _resolve_resonance_properties(
        particle_name,
        mass=component.mass,
        width=component.width,
        spin=component.spin,
        context="Three-body resonance component",
        validate_name=component.particle_name is not None,
    )


