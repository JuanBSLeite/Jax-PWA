    def _component_scale(self, component: AmplitudeComponent, values=None):
        normalize = (
            self.normalize_components
            if component.normalize_component is None
            else component.normalize_component
        )
        if not normalize:
            return 1.0
        sample = self.normalization_sample
        raw = jnp.asarray(component.function(sample.as_dict(), values))
        integral = jnp.mean(sample.weights * jnp.abs(raw) ** 2)
        return 1.0 / jnp.sqrt(integral)

    def component_amplitudes(self, data, values=None) -> dict:
        """Each component's coefficient-scaled amplitude at `data`, keyed by name.

        The terms ``amplitude()`` sums coherently: ``|component|^2`` is the
        incoherent contribution of one component (e.g. for drawing it on a
        projection), and the coherent total minus the sum of these is the
        interference.
        """
        result = {}
        for component in self.amplitude_model.components:
            dynamics = jnp.asarray(component.function(data, values))
            coefficient = jnp.asarray(coefficient_value(component.coefficient, values))
            result[component.name] = coefficient * self._component_scale(component, values) * dynamics
        return result

    def amplitude(self, data, values=None):
        """Coherent sum of every component's coefficient-scaled dynamics at `data`."""
        total = None
        for component_values in self.component_amplitudes(data, values).values():
            total = component_values if total is None else total + component_values
        return jnp.asarray(total)

    def intensity(self, data, values=None):
        """Squared magnitude of `amplitude` at `data`, i.e. |A|^2."""
        amplitude = self.amplitude(data, values)
        return jnp.real(amplitude * jnp.conj(amplitude))

    def pdf(self, normalization_sample: PhaseSpaceSample | None = None, *, efficiency=None) -> SignalPDF:
        """Build a `SignalPDF` for this model, normalized on `normalization_sample`.

        Defaults to `self.normalization_sample`; an explicit sample is validated
        as a proper integration sample first.
        """
        sample = self.normalization_sample if normalization_sample is None else normalization_sample
        if normalization_sample is not None:
            sample.validate_integration()
        def intensity(data, parameters):
            return self.intensity(data, parameters)
        kwargs = {}
        if efficiency is not None:
            kwargs["efficiency"] = efficiency
        return SignalPDF(intensity=intensity, integrator=GridIntegrator(sample), **kwargs)

    def prepare_cache(
        self,
        data_sample: PhaseSpaceSample,
        normalization_sample: PhaseSpaceSample | None = None,
        *,
        efficiency_normalization=None,
        normalize_components: bool | None = None,
    ) -> PreparedAmplitudeCache:
        """Build a `PreparedAmplitudeCache` for `data_sample` against this model.

        Reuses a cached fixed component-scale/normalization-matrix template
        when nothing floating can change it (no floating dynamics parameters,
        no efficiency normalization, and the default `normalization_sample`).
        """
        sample = self.normalization_sample if normalization_sample is None else normalization_sample
        if normalization_sample is not None:
            sample.validate_integration()
        normalize = self.normalize_components if normalize_components is None else bool(normalize_components)
        has_floating_dynamics = any(
            parameter.kind is ParameterKind.DYNAMICS and not parameter.fixed
            for parameter in self.parameters
        )

        # The common coefficient-only/no-efficiency case has a normalization
        # that depends only on the model and its fixed quadrature sample. Cache
        # the tiny scales and M_ij once, then later FitSessions evaluate only the
        # new dataset amplitudes.
        template_key = bool(normalize)
        can_reuse_normalization = (
            not has_floating_dynamics
            and efficiency_normalization is None
            and sample is self.normalization_sample
        )
        if can_reuse_normalization:
            template = self._fixed_normalization_templates.get(template_key)
            if template is not None:
                scales, matrix = template
                return PreparedAmplitudeCache.prepare_from_fixed_normalization(
                    self.amplitude_model.components,
                    data=data_sample.as_dict(),
                    normalization_weights=sample.weights,
                    parameters=self.parameters,
                    normalization_matrix_fixed=matrix,
                    component_scales=scales,
                    normalize_components=normalize,
                    compact_data_kernel=self._compact_data_kernel(
                        normalize_components=normalize
                    ),
                )

        compact_kernel = None
        if not has_floating_dynamics:
            compact_kernel = self._compact_prepare_kernel(
                normalize_components=normalize,
                has_efficiency=efficiency_normalization is not None,
            )
        cache = PreparedAmplitudeCache.prepare(
            self.amplitude_model.components,
            data=data_sample.as_dict(),
            normalization_data=sample.as_dict(),
            normalization_weights=sample.weights,
            parameters=self.parameters,
            efficiency_normalization=efficiency_normalization,
            normalize_components=normalize,
            compact_prepare_kernel=compact_kernel,
            normalization_chunk_size=self.normalization_chunk_size,
            chunk_size_memo=self._auto_chunk_memo,
        )
        if can_reuse_normalization:
            self._fixed_normalization_templates[template_key] = (
                cache.component_scales,
                cache.normalization_matrix_fixed,
            )
        return cache

    def _fraction_cache(
        self,
        normalization_sample: PhaseSpaceSample | None,
        efficiency,
    ) -> PreparedAmplitudeCache:
        sample = (
            self.normalization_sample
            if normalization_sample is None
            else normalization_sample
        )
        efficiency_values = None
        if efficiency is not None:
            efficiency_values = (
                efficiency(sample.as_dict()) if callable(efficiency) else efficiency
            )
            efficiency_values = jnp.asarray(efficiency_values)
            if efficiency_values.shape != (sample.size,):
                raise ValueError(
                    "efficiency must return one value per normalization point"
                )
        # Fit fractions use only the normalization matrix. The cache API also
        # prepares data amplitudes, so supply just one real event on that side
        # instead of duplicating the entire integration sample's preparation.
        # Keep the full normalization sample and its integration weights intact.
        data_sample = sample.take(jnp.arange(min(sample.size, 1), dtype=jnp.int32))
        return self.prepare_cache(
            data_sample,
            normalization_sample=sample,
            efficiency_normalization=efficiency_values,
        )

    def fit_fractions(
        self,
        fit_values=None,
        *,
        normalization_sample: PhaseSpaceSample | None = None,
        efficiency=None,
    ):
        """Return component fit fractions at a parameter point.

        Fractions are physical (efficiency excluded) by default. Supplying an
        efficiency returns acceptance-weighted fractions instead.
        """

        values = {} if fit_values is None else fit_values
        return self._fraction_cache(
            normalization_sample, efficiency
        ).fit_fractions(values)

    def interference_fractions(
        self,
        fit_values=None,
        *,
        normalization_sample: PhaseSpaceSample | None = None,
        efficiency=None,
    ):
        """Return pairwise interference fractions at a parameter point."""

        values = {} if fit_values is None else fit_values
        return self._fraction_cache(
            normalization_sample, efficiency
        ).interference_fractions(values)

    def print_fit_fractions(
        self,
        fit_values=None,
        *,
        normalization_sample: PhaseSpaceSample | None = None,
        efficiency=None,
        include_interference: bool = False,
        precision: int = 3,
        with_errors: bool = False,
        covariance=None,
        parameter_names: Sequence[str] | None = None,
    ) -> dict[str, float] | dict[str, object]:
        """Print fit fractions as percentages and return them by component name.

        ``with_errors=True`` -- the same flag ``FitSession``/``CPFitSession``/
        ``TimeDependentFitSession.print_fit_fractions`` expose -- additionally
        computes and prints each fraction's (and, with
        ``include_interference=True``, each interference term's) delta-method
        standard error via ``fit_fraction_errors()``/
        ``interference_fraction_errors()``, requiring a postfit ``covariance``
        (e.g. ``result.covariance`` from ``Minimizer.fit``); ``parameter_names``
        is forwarded to those methods unchanged.

        With ``with_errors=False`` and no ``include_interference``, the
        return value is the plain ``{component_name: fraction}`` dict
        (backward compatible with the no-error, no-interference call). As
        soon as either is requested, the return value instead becomes
        ``{"fractions": ..., "errors": ...?, "interference": ...?,
        "interference_errors": ...?}``, each optional key present only when
        the corresponding input was supplied/requested.
        """

        if precision < 0:
            raise ValueError("precision must be non-negative")
        if with_errors and covariance is None:
            raise ValueError("with_errors=True requires covariance")
        values = {} if fit_values is None else fit_values
        errors = (
            self.fit_fraction_errors(
                values,
                covariance,
                parameter_names,
                normalization_sample=normalization_sample,
                efficiency=efficiency,
            )
            if with_errors
            else None
        )
        interference_errors = (
            self.interference_fraction_errors(
                values,
                covariance,
                parameter_names,
                normalization_sample=normalization_sample,
                efficiency=efficiency,
            )
            if with_errors and include_interference
            else None
        )
        cache = self._fraction_cache(normalization_sample, efficiency)
        fractions = cache.fit_fractions(values)
        result = {
            component.name: float(fractions[index])
            for index, component in enumerate(cache.components)
        }
        convention = "acceptance-weighted" if efficiency is not None else "physical"
        print(f"Fit fractions ({convention})")
        if errors is None:
            print(f"{'component':24s} {'fraction [%]':>16s}")
            for name, fraction in result.items():
                print(f"{name:24s} {100.0 * fraction:16.{precision}f}")
            print(f"{'sum':24s} {100.0 * sum(result.values()):16.{precision}f}")
        else:
            print(f"{'component':24s} {'fraction [%]':>16s} {'error [%]':>16s}")
            for name, fraction in result.items():
                print(
                    f"{name:24s} {100.0 * fraction:16.{precision}f} "
                    f"{100.0 * errors.get(name, 0.0):16.{precision}f}"
                )
            print(f"{'sum':24s} {100.0 * sum(result.values()):16.{precision}f}")

        interference_result: dict[tuple[str, str], float] = {}
        if include_interference:
            interference = cache.interference_fractions(values)
            print("\nInterference fractions")
            if interference_errors is None:
                print(f"{'pair':49s} {'fraction [%]':>16s}")
            else:
                print(f"{'pair':49s} {'fraction [%]':>16s} {'error [%]':>16s}")
            for i, first in enumerate(cache.components):
                for j in range(i + 1, len(cache.components)):
                    second = cache.components[j]
                    fraction = float(interference[i, j])
                    interference_result[(first.name, second.name)] = fraction
                    if interference_errors is None:
                        print(
                            f"{first.name + ' x ' + second.name:49s} "
                            f"{100.0 * fraction:16.{precision}f}"
                        )
                    else:
                        error = interference_errors.get((first.name, second.name), 0.0)
                        print(
                            f"{first.name + ' x ' + second.name:49s} "
                            f"{100.0 * fraction:16.{precision}f} "
                            f"{100.0 * error:16.{precision}f}"
                        )

        # Plain fraction-only return by default (backward compatible); the
        # return value only grows a wrapping dict once there is something
        # extra -- errors and/or interference -- to attach to it.
        if errors is None and not include_interference:
            return result

        output: dict[str, object] = {"fractions": result}
        if errors is not None:
            output["errors"] = errors
        if include_interference:
            output["interference"] = interference_result
            if interference_errors is not None:
                output["interference_errors"] = interference_errors
        return output

    def fit_fraction_errors(
        self,
        fit_values,
        covariance,
        parameter_names: Sequence[str] | None = None,
        *,
        normalization_sample: PhaseSpaceSample | None = None,
        efficiency=None,
    ) -> dict[str, float]:
        """Delta-method standard errors for ``fit_fractions()``.

        ``fit_values`` are the postfit parameter values (e.g. from
        ``FitSession.result_values``/``CPFitSession.result_values``);
        entries missing from it fall back to each ``Parameter``'s own
        declared value, exactly like ``fit_fractions()``/
        ``print_fit_fractions()``. ``covariance`` is a postfit covariance
        matrix -- typically an ``iminuit`` ``Minuit.covariance`` (e.g.
        ``result.covariance`` from ``Minimizer.fit``) -- restricted
        internally to ``parameter_names``, which defaults to every
        non-fixed parameter in ``self.parameters``. ``normalization_sample``
        and ``efficiency`` select the same physical-vs-acceptance-weighted
        convention as ``fit_fractions()``.

        This is a linear (Gaussian) error-propagation approximation, exactly
        the one implicit in Minuit's own HESSE errors; see
        ``jaxpwa.observables.delta_method_errors``.
        """
        if parameter_names is None:
            parameter_names = tuple(
                parameter.name for parameter in self.parameters if not parameter.fixed
            )
        values = {
            parameter.name: parameter.resolve(fit_values) for parameter in self.parameters
        }
        cache = self._fraction_cache(normalization_sample, efficiency)
        jacobian = self._fraction_jacobian(cache, values, parameter_names)
        matrix = _covariance_matrix(covariance, parameter_names)
        variance = jnp.diag(jacobian @ matrix @ jacobian.T)
        errors = jnp.sqrt(jnp.clip(variance, 0.0))
        return {
            component.name: float(errors[index])
            for index, component in enumerate(cache.components)
        }

    def _fraction_jacobian(self, cache, values, parameter_names, quantity="fit_fractions"):
        names = tuple(parameter_names)
        key = (names, cache.normalize_components, cache._component_partitions(), quantity)
        kernel = self._fraction_jacobian_kernels.get(key)
        if kernel is None:
            kernel = cache._build_fraction_jacobian_kernel(names, quantity)
            self._fraction_jacobian_kernels[key] = kernel
        return kernel(values, cache._fraction_jacobian_arrays())

    def interference_fraction_errors(
        self,
        fit_values,
        covariance,
        parameter_names: Sequence[str] | None = None,
        *,
        normalization_sample: PhaseSpaceSample | None = None,
        efficiency=None,
    ) -> dict[tuple[str, str], float]:
        """Delta-method standard errors for ``interference_fractions()``.

        Same convention as ``fit_fraction_errors()`` (same ``fit_values``/
        ``covariance``/``parameter_names`` semantics, same linear-propagation
        caveat), but for the pairwise interference terms instead of the
        per-component fractions. Returned dict is keyed by
        ``(name_i, name_j)`` for every ``i < j`` pair in component order.
        """
        if parameter_names is None:
            parameter_names = tuple(
                parameter.name for parameter in self.parameters if not parameter.fixed
            )
        values = {
            parameter.name: parameter.resolve(fit_values) for parameter in self.parameters
        }
        cache = self._fraction_cache(normalization_sample, efficiency)
        jacobian, pairs = self._interference_jacobian(cache, values, parameter_names)
        matrix = _covariance_matrix(covariance, parameter_names)
        variance = jnp.diag(jacobian @ matrix @ jacobian.T)
        errors = jnp.sqrt(jnp.clip(variance, 0.0))
        return {
            (cache.components[i].name, cache.components[j].name): float(errors[index])
            for index, (i, j) in enumerate(pairs)
        }

    def _interference_jacobian(self, cache, values, parameter_names):
        names = tuple(parameter_names)
        key = (names, cache.normalize_components, cache._component_partitions())
        entry = self._interference_jacobian_kernels.get(key)
        if entry is None:
            entry = cache._build_interference_jacobian_kernel(names)
            self._interference_jacobian_kernels[key] = entry
        kernel, pairs = entry
        return kernel(values, cache._fraction_jacobian_arrays()), pairs
