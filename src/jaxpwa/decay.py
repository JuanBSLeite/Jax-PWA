@dataclass(frozen=True)
class _ResolvedDirectDynamics:
    dynamics: object

    def __call__(self, data, parameters=None):
        return resolve_value(self.dynamics, parameters)(data)

    def compact_prepared_data(self, data):
        """Delegate to the wrapped dynamics object when it can compact itself."""

        compact = getattr(self.dynamics, "compact_prepared_data", None)
        return dict(data) if compact is None else compact(data)


@dataclass(frozen=True, init=False)
class DecayModel:
    """Build a coherent amplitude model with deterministic DP normalization.

    Parameters
    ----------
    channel:
        Three-body decay channel defining masses, particle ordering, and the
        kinematic Dalitz-plot boundary.
    components:
        Coherent amplitude components: Resonance, NonResonant, or
        DalitzAmplitude objects.
    normalize_components:
        If True, each dynamical component is individually scaled by
        1/sqrt(integral |F_i|^2 dPhi) before its complex coefficient is
        applied. A component-level normalize_component value overrides this
        global default. This is a component convention; the total coherent PDF
        is still normalized separately.
    normalization_resolution:
        Nominal one-dimensional Square-Dalitz resolution. For
        normalization_method="square-dalitz", this is the standard number of
        Gauss-Legendre nodes per Square-Dalitz axis before automatic narrow-
        resonance mass-axis refinement. It is also used if conventional
        Gauss-Legendre normalization switches internally to Square Dalitz for
        a narrow m12 resonance. Default: 1000.
    normalization_method:
        Normalization coordinate/integration strategy. "gauss-legendre" uses
        tensor-product Gauss-Legendre quadrature in the conventional (m13,m23)
        mass plane. "square-dalitz" uses Gauss-Legendre quadrature in
        Square-Dalitz (m-prime, theta-prime) coordinates including the
        coordinate Jacobian. "toy-mc" uses an externally supplied
        normalization sample and its event weights directly. Supplying
        normalization_sample automatically selects "toy-mc". Narrow-resonance
        adaptation applies only to the deterministic grid methods.
    normalization_pair:
        Daughter-index pair (i,j) whose invariant mass defines the Square-
        Dalitz mass coordinate. Indices follow the daughter ordering in
        channel and must be two distinct values from 0,1,2. Default: (0,1),
        corresponding to m12.
    normalization_bin_width:
        Target broad-region mass spacing in GeV for conventional
        Gauss-Legendre normalization. If explicit axis orders are not given,
        the m13 and m23 orders are their kinematic mass ranges divided by this
        value (rounded upward). It is also the coarse scale for adaptive
        conventional-DP integration. Default: 0.005 GeV (5 MeV).
    normalization_order_m13:
        Optional explicit Gauss-Legendre order along m13 for the non-adaptive
        conventional-DP grid. None means derive it from
        normalization_bin_width. Default: None.
    normalization_order_m23:
        Optional explicit Gauss-Legendre order along m23 for the non-adaptive
        conventional-DP grid. None means derive it from
        normalization_bin_width. Default: None.
    normalization_narrow_width:
        Maximum nominal resonance width in GeV for automatic narrow-resonance
        treatment. Default: 0.020 GeV (20 MeV). The classification uses the
        declared/initial resonance parameters.
    normalization_narrow_window:
        Half-width of the fine region around a narrow pole, in units of Gamma.
        The default 5.0 gives m0 +/- 5*Gamma.
    normalization_binning_factor:
        Narrow-resonance refinement factor. The target local mass spacing is
        Gamma / normalization_binning_factor. Default: 100.0, i.e. Gamma/100.
    normalization_sample:
        Optional external Monte Carlo sample used for every normalization
        integral. The package convention is mean(sample.weights * f). A
        sample must contain integration/importance weights for its proposal.
        Unit weights are appropriate only for a proposal uniform in the target
        measure (up to its volume convention), not arbitrary signal toys.
        Use sample.with_importance_weights(q) for a known proposal density q.
        A common weight scale changes the density measure; use consistent
        conventions across components and charge samples.
    normalization_chunk_size:
        ``"auto"`` (default) or a positive integer. With floating dynamics the
        normalization is accumulated in blocks of at most this many points, so
        the memory of the reverse-AD pass does not grow with the grid size.
        ``"auto"`` measures that cost on the first normalization points
        (compile-time memory of the Hessian-vector product) and picks the
        largest block that fits half of the free device memory; without device
        memory statistics (CPU) it uses 100000. An integer overrides this.
        Coefficient-only fits use blocks of 100000 points, which only amortize
        XLA compilation. The effective block width is balanced below the limit
        to minimize padding. The chunk size changes the evaluation schedule,
        not the normalization integral.

    Notes
    -----
    The narrow-resonance integration scheme is fixed from the nominal/initial
    masses and widths and is not rebuilt while those parameters float in a fit.
    """

    channel: DecayChannel
    components: tuple[Resonance | NonResonant | DalitzAmplitude, ...]
    normalize_components: bool
    normalization_resolution: int
    normalization_method: Literal["gauss-legendre", "square-dalitz", "toy-mc"]
    normalization_pair: tuple[int, int]
    normalization_bin_width: float
    normalization_order_m13: int | None
    normalization_order_m23: int | None
    normalization_narrow_width: float
    normalization_narrow_window: float
    normalization_binning_factor: float
    normalization_chunk_size: int | str
    _auto_chunk_memo: dict[tuple, int]
    _normalization_sample: PhaseSpaceSample | None
    _amplitude_model: CoherentAmplitudeModel | None
    _compact_prepare_kernels: dict[tuple[bool, bool], object]
    _compact_data_kernels: dict[bool, object]
    _fixed_normalization_templates: dict[bool, tuple[object, object]]
    _fraction_jacobian_kernels: dict[tuple, object]
    _interference_jacobian_kernels: dict[tuple, object]

    def __init__(
        self,
        channel: DecayChannel,
        components: Iterable[Resonance | NonResonant | DalitzAmplitude],
        *,
        normalize_components: bool = True,
        normalization_resolution: int = 1000,
        normalization_method: Literal["gauss-legendre", "square-dalitz", "toy-mc"] = "gauss-legendre",
        normalization_pair: tuple[int, int] = (0, 1),
        normalization_bin_width: float = 0.005,
        normalization_order_m13: int | None = None,
        normalization_order_m23: int | None = None,
        normalization_narrow_width: float = 0.020,
        normalization_narrow_window: float = 5.0,
        normalization_binning_factor: float = 100.0,
        normalization_sample: PhaseSpaceSample | None = None,
        normalization_chunk_size: int | str = "auto",
    ) -> None:
        if normalization_resolution < 2:
            raise ValueError("normalization_resolution must be at least 2")
        if normalization_method not in ("gauss-legendre", "square-dalitz", "toy-mc"):
            raise ValueError(
                "normalization_method must be 'gauss-legendre', 'square-dalitz', or 'toy-mc'"
            )
        if normalization_sample is not None:
            if not isinstance(normalization_sample, PhaseSpaceSample):
                raise TypeError("normalization_sample must be a PhaseSpaceSample")
            normalization_sample.validate_integration()
            normalization_method = "toy-mc"
        elif normalization_method == "toy-mc":
            raise ValueError(
                "normalization_method='toy-mc' requires normalization_sample"
            )
        if len(set(normalization_pair)) != 2 or any(
            index not in (0, 1, 2) for index in normalization_pair
        ):
            raise ValueError(
                "normalization_pair must contain two distinct indices from 0, 1, 2"
            )
        if normalization_bin_width <= 0.0:
            raise ValueError("normalization_bin_width must be positive")
        if normalization_order_m13 is not None and normalization_order_m13 < 2:
            raise ValueError("normalization_order_m13 must be at least 2")
        if normalization_order_m23 is not None and normalization_order_m23 < 2:
            raise ValueError("normalization_order_m23 must be at least 2")
        if normalization_narrow_width <= 0.0:
            raise ValueError("normalization_narrow_width must be positive")
        if normalization_narrow_window <= 0.0:
            raise ValueError("normalization_narrow_window must be positive")
        if normalization_binning_factor <= 0.0:
            raise ValueError("normalization_binning_factor must be positive")
        if normalization_chunk_size != "auto" and (
            isinstance(normalization_chunk_size, bool)
            or not isinstance(normalization_chunk_size, int)
            or normalization_chunk_size < 1
        ):
            raise ValueError(
                "normalization_chunk_size must be a positive integer or 'auto'"
            )
        object.__setattr__(self, "channel", channel)
        object.__setattr__(self, "components", tuple(components))
        object.__setattr__(self, "normalize_components", bool(normalize_components))
        object.__setattr__(self, "normalization_resolution", int(normalization_resolution))
        object.__setattr__(self, "normalization_method", normalization_method)
        object.__setattr__(self, "normalization_pair", tuple(normalization_pair))
        object.__setattr__(self, "normalization_bin_width", float(normalization_bin_width))
        object.__setattr__(self, "normalization_order_m13", normalization_order_m13)
        object.__setattr__(self, "normalization_order_m23", normalization_order_m23)
        object.__setattr__(
            self, "normalization_narrow_width", float(normalization_narrow_width)
        )
        object.__setattr__(
            self, "normalization_narrow_window", float(normalization_narrow_window)
        )
        object.__setattr__(
            self, "normalization_binning_factor", float(normalization_binning_factor)
        )
        object.__setattr__(self, "normalization_chunk_size", normalization_chunk_size)
        object.__setattr__(self, "_auto_chunk_memo", {})
        object.__setattr__(self, "_normalization_sample", normalization_sample)
        object.__setattr__(self, "_amplitude_model", None)
        object.__setattr__(self, "_compact_prepare_kernels", {})
        object.__setattr__(self, "_compact_data_kernels", {})
        object.__setattr__(self, "_fixed_normalization_templates", {})
        object.__setattr__(self, "_fraction_jacobian_kernels", {})
        object.__setattr__(self, "_interference_jacobian_kernels", {})
        if not self.components:
            raise ValueError("DecayModel requires at least one amplitude component")
        names = [component.name for component in self.components]
        if len(set(names)) != len(names):
            raise ValueError("DecayModel component names must be unique")
        self._validate_parameters()

    def _validate_parameters(self) -> None:
        names: dict[str, Parameter] = {}
        dynamics_slots: dict[tuple[str, str], Parameter] = {}
        for component in self.components:
            for parameter in _collect_parameters(component):
                if parameter.name in names and names[parameter.name] != parameter:
                    raise ValueError(f"Conflicting definitions for parameter {parameter.name!r}")
                names[parameter.name] = parameter
                if parameter.kind is ParameterKind.DYNAMICS:
                    if parameter.owner != component.name:
                        raise ValueError(
                            f"Dynamics parameter {parameter.name!r} must have owner={component.name!r}"
                        )
                    backend_key = parameter.backend_name or parameter.name
                    slot = (component.name, backend_key)
                    previous = dynamics_slots.get(slot)
                    if previous is not None and previous.name != parameter.name:
                        raise ValueError(
                            "Dynamics parameters "
                            f"{previous.name!r} and {parameter.name!r} map to the same "
                            f"backend key {backend_key!r} for component {component.name!r}"
                        )
                    dynamics_slots[slot] = parameter
                if parameter.kind is ParameterKind.COEFFICIENT and parameter.owner is not None and parameter.owner != component.name:
                    raise ValueError(
                        f"Coefficient parameter {parameter.name!r} must have owner={component.name!r}"
                    )

    def _adaptive_narrow_resonances(
        self,
    ) -> dict[str, tuple[tuple[float, float], ...]]:
        """Find Laura++-style narrow bands using nominal resonance parameters.

        The integration scheme is deliberately fixed from the declared/initial
        mass and width values, matching Laura++ behaviour.  Identical-particle
        symmetrisation is expanded so a single declared resonance can refine
        more than one invariant-mass axis.
        """

        result: dict[str, set[tuple[float, float]]] = {
            "m12": set(),
            "m13": set(),
            "m23": set(),
        }
        pair_to_axis = {
            (0, 1): "m12",
            (0, 2): "m13",
            (1, 2): "m23",
        }
        masses = self.channel.daughter_masses
        final_state_ids = self.channel.final_state_ids

        for component in self.components:
            if not isinstance(component, Resonance):
                continue

            resolved_mass, resolved_width, _ = _resolved_resonance_properties(
                component
            )
            nominal_mass = _nominal_float(resolved_mass, 0.0)
            nominal_width = _nominal_float(resolved_width, 0.0)
            if (
                nominal_width <= 0.0
                or nominal_width > self.normalization_narrow_width
            ):
                continue

            for pair in _symmetrized_mass_pairs(component.pair, final_state_ids):
                bachelor = next(index for index in range(3) if index not in pair)
                low = masses[pair[0]] + masses[pair[1]]
                high = self.channel.parent_mass - masses[bachelor]
                if nominal_mass < low or nominal_mass > high:
                    continue
                result[pair_to_axis[pair]].add((nominal_mass, nominal_width))

        return {
            axis: tuple(sorted(values))
            for axis, values in result.items()
        }

    def _flatten_narrow_resonances(
        self,
        narrow: dict[str, tuple[tuple[float, float], ...]] | None = None,
    ) -> tuple[tuple[tuple[int, int], float, float], ...]:
        """Return unique narrow bands as (pair, pole_mass, pole_width)."""

        values = self._adaptive_narrow_resonances() if narrow is None else narrow
        axis_to_pair = {
            "m12": (0, 1),
            "m13": (0, 2),
            "m23": (1, 2),
        }
        flattened = []
        for axis, pair in axis_to_pair.items():
            for mass, width in values[axis]:
                flattened.append((pair, mass, width))
        return tuple(flattened)

    @staticmethod
    def _format_narrow_bands(
        narrow: dict[str, tuple[tuple[float, float], ...]],
    ) -> str:
        entries = []
        for axis in ("m12", "m13", "m23"):
            for mass, width in narrow[axis]:
                entries.append(
                    f"{axis}: m0={mass:.6f} GeV, Gamma={1000.0 * width:.3f} MeV"
                )
        return "; ".join(entries)

    @property
    def normalization_scheme(self) -> dict[str, object]:
        """Describe the active normalization strategy."""

        if self.normalization_method == "toy-mc":
            sample = self.normalization_sample
            return {
                "method": "toy-mc",
                "adaptive": False,
                "sample_size": sample.size,
                "weighted": bool(jnp.any(jnp.asarray(sample.weights) != 1.0)),
                "chunk_size": self.normalization_chunk_size,
            }

        narrow = self._adaptive_narrow_resonances()
        has_narrow = any(narrow[axis] for axis in ("m12", "m13", "m23"))

        if not has_narrow:
            if self.normalization_method == "gauss-legendre":
                return {
                    "method": "gauss-legendre",
                    "adaptive": False,
                    "bin_width": self.normalization_bin_width,
                    "order_m13": self.normalization_order_m13,
                    "order_m23": self.normalization_order_m23,
                }
            return {
                "method": "square-dalitz",
                "adaptive": False,
                "pair": self.normalization_pair,
                "resolution": self.normalization_resolution,
            }

        if self.normalization_method == "gauss-legendre" and not narrow["m12"]:
            grid = AdaptiveDalitzGaussLegendreGrid(
                self.channel.parent_mass,
                self.channel.daughter_masses,
                m13_narrow_resonances=narrow["m13"],
                m23_narrow_resonances=narrow["m23"],
                bin_width=self.normalization_bin_width,
                narrow_width=self.normalization_narrow_width,
                window_n_widths=self.normalization_narrow_window,
                binning_factor=self.normalization_binning_factor,
            )
            return {
                "method": "gauss-legendre",
                "adaptive": True,
                "internal_coordinates": "m13-m23",
                "narrow_resonances": narrow,
                "m13_segments": grid.m13_segments,
                "m23_segments": grid.m23_segments,
                "estimated_tensor_points": grid.estimated_tensor_points,
            }

        if self.normalization_method == "gauss-legendre":
            return {
                "method": "gauss-legendre",
                "adaptive": True,
                "internal_coordinates": "square-dalitz",
                "reason": "narrow m12 band is diagonal in the conventional m13-m23 plane",
                "pair": (0, 1),
                "resolution": self.normalization_resolution,
                "narrow_resonances": narrow,
            }

        square_grid = AdaptiveSquareDalitzGrid(
            self.channel.parent_mass,
            self.channel.daughter_masses,
            narrow_resonances=self._flatten_narrow_resonances(narrow),
            resolution=self.normalization_resolution,
            pair=self.normalization_pair,
            window_n_widths=self.normalization_narrow_window,
            binning_factor=self.normalization_binning_factor,
        )
        return {
            "method": "square-dalitz",
            "adaptive": bool(square_grid.aligned_narrow_resonances),
            "adaptive_axis": "mprime",
            "pair": self.normalization_pair,
            "theta_resolution": self.normalization_resolution,
            "mprime_nodes": square_grid.mprime_node_count,
            "estimated_points": square_grid.estimated_points,
            "aligned_narrow_resonances": square_grid.aligned_narrow_resonances,
            "crossed_narrow_resonances": square_grid.crossed_narrow_resonances,
            "narrow_resonances": narrow,
        }

    @property
    def parameters(self) -> tuple[Parameter, ...]:
        """All `Parameter`s referenced by `components`, deduplicated by name."""
        unique: dict[str, Parameter] = {}
        for component in self.components:
            for parameter in _collect_parameters(component):
                unique.setdefault(parameter.name, parameter)
        return tuple(unique.values())

    def with_fixed_parameters(
        self,
        *names: str,
        values: Mapping[str, float] | None = None,
    ) -> DecayModel:
        """Return a new model with selected parameters fixed.

        Positional names retain their current values. Entries in ``values``
        are assigned the supplied value and fixed. The original model and its
        parameters remain unchanged.
        """
        updates = _fixed_parameter_updates(self.parameters, names, values)
        components = _replace_fixed_parameters(self.components, updates)
        normalization_sample = (
            self._normalization_sample
            if self.normalization_method == "toy-mc"
            else None
        )
        return DecayModel(
            self.channel,
            components,
            normalize_components=self.normalize_components,
            normalization_resolution=self.normalization_resolution,
            normalization_method=self.normalization_method,
            normalization_pair=self.normalization_pair,
            normalization_bin_width=self.normalization_bin_width,
            normalization_order_m13=self.normalization_order_m13,
            normalization_order_m23=self.normalization_order_m23,
            normalization_narrow_width=self.normalization_narrow_width,
            normalization_narrow_window=self.normalization_narrow_window,
            normalization_binning_factor=self.normalization_binning_factor,
            normalization_sample=normalization_sample,
            normalization_chunk_size=self.normalization_chunk_size,
        )

    @property
    def normalization_sample(self) -> PhaseSpaceSample:
        """Deterministic quadrature sample used to normalize the amplitude model.

        Built lazily from `normalization_method` (with automatic narrow-resonance
        grid refinement) and cached on first access.
        """
        sample = self._normalization_sample
        if sample is None:
            narrow = self._adaptive_narrow_resonances()
            has_narrow = any(
                narrow[axis] for axis in ("m12", "m13", "m23")
            )

            if self.normalization_method == "gauss-legendre":
                if not has_narrow:
                    sample = DalitzGaussLegendreGrid(
                        self.channel.parent_mass,
                        self.channel.daughter_masses,
                        bin_width=self.normalization_bin_width,
                        order_m13=self.normalization_order_m13,
                        order_m23=self.normalization_order_m23,
                    ).sample()
                elif narrow["m12"]:
                    grid = AdaptiveSquareDalitzGrid(
                        self.channel.parent_mass,
                        self.channel.daughter_masses,
                        narrow_resonances=self._flatten_narrow_resonances(narrow),
                        resolution=self.normalization_resolution,
                        pair=(0, 1),
                        window_n_widths=self.normalization_narrow_window,
                        binning_factor=self.normalization_binning_factor,
                    )
                    print(
                        "INFO Jax-PWA normalization: narrow resonance "
                        "band(s) detected ("
                        + self._format_narrow_bands(narrow)
                        + "); using Square-Dalitz coordinates internally because "
                        "m12 is diagonal in the conventional m13-m23 plane. "
                        "Adaptive refinement is applied only along the mass "
                        f"axis m': {grid.mprime_node_count} m' nodes x "
                        f"{self.normalization_resolution} theta' nodes "
                        f"({grid.estimated_points:,} points)."
                    )
                    sample = grid.sample()
                else:
                    print(
                        "INFO Jax-PWA normalization: narrow resonance "
                        "band(s) detected ("
                        + self._format_narrow_bands(narrow)
                        + "); using adaptive Gauss-Legendre normalization."
                    )
                    sample = AdaptiveDalitzGaussLegendreGrid(
                        self.channel.parent_mass,
                        self.channel.daughter_masses,
                        m13_narrow_resonances=narrow["m13"],
                        m23_narrow_resonances=narrow["m23"],
                        bin_width=self.normalization_bin_width,
                        narrow_width=self.normalization_narrow_width,
                        window_n_widths=self.normalization_narrow_window,
                        binning_factor=self.normalization_binning_factor,
                    ).sample()
            else:
                if not has_narrow:
                    sample = SquareDalitzGrid(
                        self.channel.parent_mass,
                        self.channel.daughter_masses,
                        resolution=self.normalization_resolution,
                        pair=self.normalization_pair,
                        quadrature="gauss-legendre",
                    ).sample()
                else:
                    grid = AdaptiveSquareDalitzGrid(
                        self.channel.parent_mass,
                        self.channel.daughter_masses,
                        narrow_resonances=self._flatten_narrow_resonances(narrow),
                        resolution=self.normalization_resolution,
                        pair=self.normalization_pair,
                        window_n_widths=self.normalization_narrow_window,
                        binning_factor=self.normalization_binning_factor,
                    )
                    if grid.aligned_narrow_resonances:
                        print(
                            "INFO Jax-PWA normalization: narrow resonance "
                            "band(s) detected ("
                            + self._format_narrow_bands(narrow)
                            + "); applying adaptive Square-Dalitz refinement only "
                            "along the mass axis m'. "
                            f"Grid: {grid.mprime_node_count} m' nodes x "
                            f"{self.normalization_resolution} theta' nodes "
                            f"({grid.estimated_points:,} points; base "
                            f"{self.normalization_resolution**2:,})."
                        )
                        if grid.crossed_narrow_resonances:
                            print(
                                "INFO Jax-PWA normalization: crossed narrow "
                                "band(s) are kept on the standard theta' resolution; "
                                "only resonances aligned with normalization_pair "
                                "refine m'."
                            )
                        sample = grid.sample()
                    else:
                        print(
                            "INFO Jax-PWA normalization: narrow resonance "
                            "band(s) detected, but none is aligned with the selected "
                            "Square-Dalitz mass pair; keeping the standard "
                            f"{self.normalization_resolution} x "
                            f"{self.normalization_resolution} grid."
                        )
                        sample = SquareDalitzGrid(
                            self.channel.parent_mass,
                            self.channel.daughter_masses,
                            resolution=self.normalization_resolution,
                            pair=self.normalization_pair,
                            quadrature="gauss-legendre",
                        ).sample()

            object.__setattr__(self, "_normalization_sample", sample)
        return sample

    def _build_resonance(self, component: Resonance) -> AmplitudeComponent:
        i, j = component.pair
        bachelor = next(index for index in range(3) if index not in component.pair)
        masses = self.channel.daughter_masses
        mass0, width0, spin = _resolved_resonance_properties(component)
        context = ResonanceContext(
            parent_mass=self.channel.parent_mass,
            daughter_masses=(masses[i], masses[j]),
            bachelor_mass=masses[bachelor],
            spin=spin,
            pole_mass=mass0,
            pole_width=width0,
            resonance_radius=component.resonance_radius,
            parent_radius=component.parent_radius,
        )
        dynamics = ResonanceAmplitude(
            context=context,
            daughter_key=f"p{i + 1}",
            partner_key=f"p{j + 1}",
            bachelor_key=f"p{bachelor + 1}",
            final_state=self.channel.final_state_ids,
            lineshape=component.lineshape,
            angular=component.angular,
            bachelor_momentum_frame=component.bachelor_momentum_frame,
            normalize_form_factors=component.normalize_form_factors,
        )
        return AmplitudeComponent(
            component.name,
            dynamics,
            component.coefficient,
            component.normalize_component,
        )

    @property
    def amplitude_model(self) -> CoherentAmplitudeModel:
        """Built `CoherentAmplitudeModel`, resolving each declared component's dynamics.

        Built lazily from `components` (`Resonance`, `NonResonant`, `DalitzAmplitude`)
        and cached on first access.
        """
        model = self._amplitude_model
        if model is not None:
            return model
        built = []
        for component in self.components:
            if isinstance(component, Resonance):
                built.append(self._build_resonance(component))
            elif isinstance(component, NonResonant):
                built.append(
                    AmplitudeComponent(
                        component.name,
                        ConstantAmplitude(),
                        component.coefficient,
                        component.normalize_component,
                    )
                )
            elif isinstance(component, DalitzAmplitude):
                built.append(
                    AmplitudeComponent(
                        component.name,
                        _ResolvedDirectDynamics(component.dynamics),
                        component.coefficient,
                        component.normalize_component,
                    )
                )
            else:
                raise TypeError(f"Unsupported amplitude component: {type(component)!r}")
        model = CoherentAmplitudeModel(tuple(built))
        object.__setattr__(self, "_amplitude_model", model)
        return model

    def _compact_prepare_kernel(self, *, normalize_components: bool, has_efficiency: bool):
        key = (bool(normalize_components), bool(has_efficiency))
        kernel = self._compact_prepare_kernels.get(key)
        if kernel is None:
            kernel = PreparedAmplitudeCache.build_compact_prepare_kernel(
                self.amplitude_model.components,
                normalize_components=normalize_components,
                has_efficiency=has_efficiency,
                compact_data_kernel=self._compact_data_kernel(
                    normalize_components=normalize_components,
                ),
                normalization_chunk_size=(
                    DEFAULT_NORMALIZATION_CHUNK_SIZE
                    if self.normalization_chunk_size == "auto"
                    else self.normalization_chunk_size
                ),
            )
            self._compact_prepare_kernels[key] = kernel
        return kernel

    def _compact_data_kernel(self, *, normalize_components: bool):
        key = bool(normalize_components)
        kernel = self._compact_data_kernels.get(key)
        if kernel is None:
            kernel = PreparedAmplitudeCache.build_compact_data_kernel(
                self.amplitude_model.components,
                normalize_components=normalize_components,
            )
            self._compact_data_kernels[key] = kernel
        return kernel

